    CREATE TABLE IF NOT EXISTS patients (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(100) NOT NULL,
        age INTEGER NOT NULL,
        gender VARCHAR(20) NOT NULL,
        phone VARCHAR(20) NOT NULL,
        email VARCHAR(255),
        address VARCHAR(255),
        disease VARCHAR(255),
        status VARCHAR(30) NOT NULL
    );

    CREATE INDEX IF NOT EXISTS ix_patients_id ON patients (id);
    CREATE INDEX IF NOT EXISTS ix_patients_phone ON patients (phone);

    CREATE TABLE IF NOT EXISTS doctors (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(100) NOT NULL,
        specialization VARCHAR(100) NOT NULL,
        phone VARCHAR(20) NOT NULL,
        email VARCHAR(255),
        experience INTEGER,
        status VARCHAR(30) NOT NULL
    );

    CREATE INDEX IF NOT EXISTS ix_doctors_id ON doctors (id);

    CREATE TABLE IF NOT EXISTS assignments (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        patient_id INTEGER NOT NULL REFERENCES patients (id),
        doctor_id INTEGER NOT NULL REFERENCES doctors (id),
        status VARCHAR(30) NOT NULL,
        assigned_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
        released_at TIMESTAMP WITHOUT TIME ZONE
    );

    CREATE INDEX IF NOT EXISTS ix_assignments_id ON assignments (id);
    CREATE INDEX IF NOT EXISTS ix_assignments_doctor_id ON assignments (doctor_id);
    CREATE INDEX IF NOT EXISTS ix_assignments_patient_id ON assignments (patient_id);
